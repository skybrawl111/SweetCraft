import docx
from docx.shared import Pt, Inches, RGBColor, Mm
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT, WD_ALIGN_VERTICAL
from docx.oxml import OxmlElement, parse_xml
from docx.oxml.ns import nsdecls, qn

def build_report_day2():
    doc = docx.Document()
    
    # Поля страницы по ГОСТ (Левое 30 мм, Правое 15 мм, Верхнее 20 мм, Нижнее 20 мм)
    sec = doc.sections[0]
    sec.top_margin = Mm(20)
    sec.bottom_margin = Mm(20)
    sec.left_margin = Mm(30)
    sec.right_margin = Mm(15)
    sec.page_width = Mm(210)
    sec.page_height = Mm(297)
    
    # Нумерация страниц со 2-й страницы
    sec.different_first_page_header_footer = True
    footer = sec.footer
    f_p = footer.paragraphs[0]
    f_p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    f_run = f_p.add_run()
    f_run.font.name = 'Times New Roman'
    f_run.font.size = Pt(10)
    f_run.font.color.rgb = RGBColor(100, 100, 100)
    
    fld1 = parse_xml(r'<w:fldChar %s w:fldCharType="begin"/>' % nsdecls('w'))
    instr = parse_xml(r'<w:instrText %s xml:space="preserve"> PAGE </w:instrText>' % nsdecls('w'))
    fld2 = parse_xml(r'<w:fldChar %s w:fldCharType="separate"/>' % nsdecls('w'))
    fld3 = parse_xml(r'<w:fldChar %s w:fldCharType="end"/>' % nsdecls('w'))
    f_run._r.append(fld1)
    f_run._r.append(instr)
    f_run._r.append(fld2)
    f_run._r.append(fld3)

    def format_p(p, before=0, after=6, spacing=1.5, indent=1.25, align=WD_ALIGN_PARAGRAPH.JUSTIFY):
        p.paragraph_format.space_before = Pt(before)
        p.paragraph_format.space_after = Pt(after)
        p.paragraph_format.line_spacing = spacing
        p.paragraph_format.first_line_indent = Mm(indent) if indent else 0
        p.alignment = align

    def p(text="", bold=False, italic=False, size=14, before=0, after=6, spacing=1.5, indent=1.25, align=WD_ALIGN_PARAGRAPH.JUSTIFY):
        prg = doc.add_paragraph()
        format_p(prg, before, after, spacing, indent, align)
        if text:
            r = prg.add_run(text)
            r.bold = bold
            r.italic = italic
            r.font.name = 'Times New Roman'
            r.font.size = Pt(size)
            r.font.color.rgb = RGBColor(0, 0, 0)
        return prg

    def h1(text):
        prg = doc.add_paragraph()
        format_p(prg, before=18, after=8, spacing=1.5, indent=0, align=WD_ALIGN_PARAGRAPH.LEFT)
        r = prg.add_run(text)
        r.bold = True
        r.font.name = 'Times New Roman'
        r.font.size = Pt(15)
        r.font.color.rgb = RGBColor(0, 51, 102)
        return prg

    def h2(text):
        prg = doc.add_paragraph()
        format_p(prg, before=12, after=6, spacing=1.5, indent=0, align=WD_ALIGN_PARAGRAPH.LEFT)
        r = prg.add_run(text)
        r.bold = True
        r.font.name = 'Times New Roman'
        r.font.size = Pt(14)
        r.font.color.rgb = RGBColor(20, 20, 20)
        return prg

    def bullet(lead, text):
        prg = doc.add_paragraph()
        format_p(prg, before=0, after=4, spacing=1.5, indent=1.25, align=WD_ALIGN_PARAGRAPH.JUSTIFY)
        r1 = prg.add_run(lead)
        r1.bold = True
        r1.font.name = 'Times New Roman'
        r1.font.size = Pt(14)
        r2 = prg.add_run(text)
        r2.font.name = 'Times New Roman'
        r2.font.size = Pt(14)
        return prg

    def add_image_box(img_path, caption_text):
        if os.path.exists(img_path):
            p_img = doc.add_paragraph()
            p_img.alignment = WD_ALIGN_PARAGRAPH.CENTER
            p_img.paragraph_format.space_before = Pt(8)
            p_img.paragraph_format.space_after = Pt(4)
            p_img.paragraph_format.first_line_indent = 0
            run = p_img.add_run()
            run.add_picture(img_path, width=Mm(162))
            
            p_cap = doc.add_paragraph()
            p_cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
            p_cap.paragraph_format.space_before = Pt(0)
            p_cap.paragraph_format.space_after = Pt(8)
            p_cap.paragraph_format.first_line_indent = 0
            r_cap = p_cap.add_run(caption_text)
            r_cap.font.name = 'Times New Roman'
            r_cap.font.size = Pt(11)
            r_cap.italic = True
            r_cap.font.color.rgb = RGBColor(70, 70, 70)

    def style_table(table, col_widths, header_bg="EAF0F6"):
        tblPr = table._tbl.tblPr
        borders = parse_xml(f'''
            <w:tblBorders {nsdecls("w")}>
                <w:top w:val="single" w:sz="4" w:space="0" w:color="999999"/>
                <w:left w:val="single" w:sz="4" w:space="0" w:color="999999"/>
                <w:bottom w:val="single" w:sz="4" w:space="0" w:color="999999"/>
                <w:right w:val="single" w:sz="4" w:space="0" w:color="999999"/>
                <w:insideH w:val="single" w:sz="4" w:space="0" w:color="CCCCCC"/>
                <w:insideV w:val="single" w:sz="4" w:space="0" w:color="CCCCCC"/>
            </w:tblBorders>
        ''')
        tblPr.append(borders)
        table.alignment = WD_TABLE_ALIGNMENT.CENTER
        
        for i, row in enumerate(table.rows):
            is_h = (i == 0)
            trPr = row._tr.get_or_add_trPr()
            trPr.append(parse_xml(f'<w:cantSplit {nsdecls("w")}/>'))
            if is_h:
                trPr.append(parse_xml(f'<w:tblHeader {nsdecls("w")}/>'))
            for j, cell in enumerate(row.cells):
                if j < len(col_widths):
                    cell.width = Mm(col_widths[j])
                cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
                tcPr = cell._tc.get_or_add_tcPr()
                tcMar = OxmlElement('w:tcMar')
                for m, val in [('top', 100), ('bottom', 100), ('left', 140), ('right', 140)]:
                    node = OxmlElement(f'w:{m}')
                    node.set(qn('w:w'), str(val))
                    node.set(qn('w:type'), 'dxa')
                    tcMar.append(node)
                tcPr.append(tcMar)
                if is_h:
                    shd = parse_xml(f'<w:shd {nsdecls("w")} w:fill="{header_bg}"/>')
                    tcPr.append(shd)
                for prg in cell.paragraphs:
                    prg.paragraph_format.space_before = Pt(2)
                    prg.paragraph_format.space_after = Pt(2)
                    prg.paragraph_format.line_spacing = 1.15
                    prg.paragraph_format.first_line_indent = 0
                    if is_h:
                        prg.alignment = WD_ALIGN_PARAGRAPH.CENTER
                        for r in prg.runs:
                            r.bold = True
                            r.font.name = 'Times New Roman'
                            r.font.size = Pt(10)
                    else:
                        for r in prg.runs:
                            r.font.name = 'Times New Roman'
                            r.font.size = Pt(9.5)

