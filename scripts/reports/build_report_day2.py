    h2("1.2. Процесс 2: «Планирование смен цеха и установка суточных лимитов выпечки»")
    p("Этот процесс отвечает за реализацию Особого требования моего варианта № 1 — жесткий контроль суточного веса выпечки цеха для исключения срыва сроков.")
    bullet("Границы процесса:", " начинается с наступления планового периода формирования графика (за 2–3 недели до начала месяца); завершается сохранением суточных лимитов выпечки (в кг) в базе данных системы.")
    bullet("Участники и роли:", " Шеф-кондитер (управляющий производством), Администратор системы.")
    bullet("Входные данные:", " рабочий график мастеров-кондитеров, производственный календарь выходных и праздничных дней, техническая норма выработки цеха (35 кг в будни, 45 кг в усиленную смену).")
