    p("ОТЧЕТ ПО ПРОИЗВОДСТВЕННОЙ ПРАКТИКЕ", bold=True, size=16, before=40, after=8, spacing=1.15, indent=0, align=WD_ALIGN_PARAGRAPH.CENTER)
    p("Занятие № 2. Описание бизнес-процессов предметной области", bold=True, size=14, before=0, after=20, spacing=1.15, indent=0, align=WD_ALIGN_PARAGRAPH.CENTER)
    
    p("Тема проекта: «Разработка веб-сервиса приема индивидуальных заказов на торты и десерты с контролем производственной мощности кондитерского цеха»", italic=True, size=13, before=0, after=24, spacing=1.15, indent=0, align=WD_ALIGN_PARAGRAPH.CENTER)
    
    p("Вариант индивидуального задания: № 1 («Заказ тортов и десертов в кондитерской»)", bold=True, size=13, before=0, after=12, spacing=1.15, indent=0, align=WD_ALIGN_PARAGRAPH.CENTER)
    p("Специальность: 09.02.07 «Информационные системы и программирование»", size=12, before=0, after=6, spacing=1.15, indent=0, align=WD_ALIGN_PARAGRAPH.CENTER)
    p("Курс: 4", size=12, before=0, after=6, spacing=1.15, indent=0, align=WD_ALIGN_PARAGRAPH.CENTER)
    
    p("", before=60, after=0)
    
