    bullet("Выходные данные:", " зарегистрированный заказ со статусом «Принят в работу», забронированный вес в суточной смене цеха, электронная технологическая карта с фото, email-уведомление клиенту.")
    bullet("Частота выполнения:", " ежедневно в течение всего рабочего дня (в среднем от 8 до 15 заказов в сутки, в предпраздничные дни — до 30 заказов).")
