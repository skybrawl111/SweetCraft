    h1("2. Графическое моделирование бизнес-процессов в нотации BPMN 2.0")
    p("Для визуализации процессов я использовал общепринятую нотацию BPMN 2.0. Все диаграммы спроектированы с разделением на пулы и дорожки (swimlanes), что позволяет наглядно показать, кто именно выполняет каждую операцию. Развилки оформлены шлюзами исключающего «ИЛИ» (Exclusive Gateway / XOR) с обязательными подписями условий на исходящих потоках, а действия названы строго по правилу «глагол + существительное».")

    h2("2.1. Главный процесс As-Is («Как есть» до внедрения системы)")
    p("На рисунке 1 представлена схема главного процесса в том виде, как сейчас работают небольшие крафтовые кондитерские студии. Схема наглядно вскрывает главную проблему — огромное количество ручных передач информации между клиентом в мессенджере, менеджером с калькулятором и кондитером у печи.")

