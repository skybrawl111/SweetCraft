def add_caption(doc, text, is_table=True):
    align = WD_ALIGN_PARAGRAPH.LEFT if is_table else WD_ALIGN_PARAGRAPH.CENTER
    return add_paragraph_styled(doc, text=text, space_before=8, space_after=4, line_spacing=1.15,
                                first_indent=0, align=align, bold=True, italic=(not is_table),
                                font_size=11, color_rgb=(0, 0, 0))

def add_figure_image(doc, img_path, caption_text, width_inches=6.2):
    """
    Вставляет фактический скриншот или диаграмму с выравниванием по центру
    и обязательной подписью под рисунком по ГОСТ.
    """
    p_img = doc.add_paragraph()
    p_img.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p_img.paragraph_format.space_before = Pt(8)
    p_img.paragraph_format.space_after = Pt(4)
    p_img.paragraph_format.first_line_indent = Cm(0)
    p_img.paragraph_format.line_spacing = 1.0
    p_img.paragraph_format.keep_with_next = True

    resolved_path = Path(img_path)
    if not resolved_path.is_absolute():
        resolved_path = BASE_DIR / resolved_path

    if resolved_path.exists():
        run = p_img.add_run()
        run.add_picture(str(resolved_path), width=Inches(width_inches))
    else:
        run = p_img.add_run(f"[Изображение не найдено: {resolved_path.name}]")
        run.bold = True
        run.font.name = 'Times New Roman'
        run.font.size = Pt(11)

    add_caption(doc, caption_text, is_table=False)

